/* SubX hub: render highlights.json + rooms.json + stories.json (built by hub/src/build_highlights.py). Read-only:
   no writes, no auth. The composer and Add story only hand off to a room (https://<room>/#compose=<text> or #story). Generated by tools/brand_render.py from brand/brand.json; edit hub/src/templates/hub.js, not hub/site.
   Each part runs on its own: the home page has #hub-feed (+ #hub-rooms tab), rooms.html has only #hub-rooms. */
(function () {
  'use strict';
  var ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
  function esc(s) { return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) { return ESC[c]; }); }
  function safeUrl(u) { return /^https:\/\/[a-z0-9.-]+\.[a-z]{2,}\/(\?p=[A-Za-z0-9_-]+)?$/i.test(String(u || '')) ? u : ''; }
  var COLORS = ['#121214', '#a11d33', '#3a3a40', '#7d1426', '#5a554c', '#26262b'];
  function color(key) { var h = 0; key = String(key || ''); for (var i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) >>> 0; return COLORS[h % COLORS.length]; }
  function initials(name) { var w = String(name || '?').trim().split(/\s+/); return ((w[0] || '?').charAt(0) + (w[1] ? w[1].charAt(0) : '')).toUpperCase(); }
  function ago(iso) {
    var t = Date.parse(iso); if (!isFinite(t)) return '';
    var s = Math.max(0, (Date.now() - t) / 1000);
    if (s < 3600) return Math.max(1, Math.round(s / 60)) + 'm';
    if (s < 86400) return Math.round(s / 3600) + 'h';
    if (s < 86400 * 30) return Math.round(s / 86400) + 'd';
    return new Date(t).toLocaleDateString(undefined, { month: 'short', day: 'numeric' });
  }
  function tierHtml(tier, names) {
    // Every highlight carries its WHOMARK™ label; whomark.js upgrades the span to the mark + visible label.
    // Text fallback (no JS for the upgrade) is the same visible label.
    if (tier === 'ai') return '<span class="hub-tier" data-whomark="ai" data-whomark-steward="true">AI-made · AI steward</span>';
    if (tier === 'human') return '<span class="hub-tier" data-whomark="human">Human-made</span>';
    if (tier === 'hybrid') return '<span class="hub-tier" data-whomark="hybrid" data-whomark-names="' + esc(names || '') + '">Human + AI</span>';
    return '';
  }
  function card(it) {
    var url = safeUrl(it.url); if (!url) return '';
    var who = it.authorName || it.roomName;
    return '<a class="hub-card" href="' + esc(url) + '" rel="noopener" data-room="' + esc(it.room) + '">' +
      '<div class="post-avatar" style="background:' + color(it.room) + '" aria-hidden="true">' + esc(initials(who)) + '</div>' +
      '<div class="post-body"><div class="post-meta">' +
      '<span class="post-name">' + esc(who) + '</span>' + tierHtml(it.tier, it.names) +
      (it.authorHandle ? '<span class="post-handle">@' + esc(it.authorHandle) + '</span>' : '') +
      '<span class="post-time">· ' + esc(ago(it.createdAt)) + '</span></div>' +
      '<div class="hub-room">in ' + esc(it.roomName) + '</div>' +
      '<div class="post-text">' + esc(it.text) + '</div>' +
      '<div class="hub-open">Open in ' + esc(it.domain) + ' →</div></div></a>';
  }
  function roomCard(r) {
    var url = safeUrl('https://' + r.domain + '/'); if (!url) return '';
    return '<a class="hub-room-card' + (r.featured ? ' is-featured' : '') + '" href="' + esc(url) + '" rel="noopener"><strong>' + esc(r.name) + '</strong>' +
      (r.featured ? '<span class="hub-feat-tag">Featured</span>' : '') +
      '<span class="hub-room-domain">' + esc(r.domain) + '</span>' + (r.tagline ? '<p>' + esc(r.tagline) + '</p>' : '') + '</a>';
  }
  function getJSON(p) { return fetch(p, { cache: 'no-cache' }).then(function (r) { if (!r.ok) throw new Error(p + ' ' + r.status); return r.json(); }); }
  var feed = document.getElementById('hub-feed'), roomsEl = document.getElementById('hub-rooms'), coming = document.getElementById('hub-coming');
  if (feed) {
    getJSON('/highlights.json?v=d9dc228224').then(function (d) {
      var items = (d && d.items) || [];
      var feat = items.filter(function (it) { return it.featured; }), rest = items.filter(function (it) { return !it.featured; });
      var html = (feat.length ? '<h2 class="hub-section">Featured rooms</h2>' + feat.map(card).join('') : '') +
        (rest.length ? '<h2 class="hub-section">Also from the rooms</h2>' + rest.map(card).join('') : '');
      var when = d && d.generated ? new Date(d.generated).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' }) : '';
      feed.innerHTML = (html || '<div class="post-empty">No highlights yet. Open a room to read or post.</div>') +
        '<div class="hub-foot">Highlights are public posts copied at build time' + (when ? ' (' + esc(when) + ')' : '') +
        '. Hidden, reported, and reply posts are left out, and paused rooms are not shown. Report a post from its room, or see <a href="/report.html">Report</a>.</div>';
    }).catch(function () { feed.innerHTML = '<div class="post-empty">Highlights are unavailable right now. Open a room from the list.</div>'; });
  }
  if (roomsEl) {
    getJSON('/rooms.json?v=2fcf997cfb').then(function (d) {
      roomsEl.innerHTML = ((d && d.rooms) || []).map(roomCard).join('') || '<div class="post-empty">No rooms listed.</div>';
    }).catch(function () { roomsEl.innerHTML = '<div class="post-empty">Rooms are unavailable right now.</div>'; });
  }
  // Stories row + composer (2026-11-04). Nothing is sent or stored by the hub: the text rides in the URL fragment
  // (never sent to any server) to the room, whose shell (v1.2.7+) fills its composer; it is also copied as a fallback.
  function domainOk(d) { return /^[a-z0-9-]+(\.[a-z0-9-]+)*\.[a-z]{2,}$/i.test(String(d || '')); }
  function roomHref(d, frag) { return domainOk(d) ? 'https://' + d + '/' + (frag ? '#' + frag : '') : ''; }
  function msOf(v) { return typeof v === 'number' ? v : Date.parse(v); }
  function openDlg(el) { if (!el) return; el.hidden = false; var f = el.querySelector('a,button'); if (f) f.focus(); }
  function closeDlgs() { Array.prototype.forEach.call(document.querySelectorAll('.hub-pick'), function (x) { x.hidden = true; }); }
  document.addEventListener('keydown', function (e) { if (e.key === 'Escape') closeDlgs(); });
  Array.prototype.forEach.call(document.querySelectorAll('.hub-pick'), function (el) {
    el.addEventListener('click', function (e) { if (e.target === el || e.target.hasAttribute('data-hub-close')) closeDlgs(); });
  });
  var row = document.getElementById('hub-stories-row'), addBtn = document.getElementById('hub-story-add');
  var pick = document.getElementById('hub-story-pick'), pickList = document.getElementById('hub-story-pick-list');
  var view = document.getElementById('hub-story-view'), cards = document.getElementById('hub-story-cards');
  var viewTitle = document.getElementById('hub-story-view-title');
  if (row) {
    getJSON('/stories.json?v=a79f5dfcad').then(function (d) {
      var now = Date.now(), byRoom = {};
      ((d && d.items) || []).forEach(function (it) {
        if (!(msOf(it.expiresAt) > now) || !domainOk(it.domain)) return;
        (byRoom[it.room] = byRoom[it.room] || []).push(it);
      });
      var rooms = ((d && d.rooms) || []).filter(function (r) { return r.stories && domainOk(r.domain); });
      rooms.sort(function (a, b) { return (byRoom[b.room] ? 1 : 0) - (byRoom[a.room] ? 1 : 0); });
      pickList.innerHTML = rooms.map(function (r) {
        return '<a class="hub-pick-room" href="' + esc(roomHref(r.domain, 'story')) + '" rel="noopener"><strong>' + esc(r.name) + '</strong><span>' + esc(r.domain) + '</span></a>';
      }).join('') || '<div class="post-empty">No room has Stories on right now.</div>';
      row.insertAdjacentHTML('beforeend', rooms.map(function (r) {
        var live = byRoom[r.room];
        return '<button type="button" class="hub-story' + (live ? ' has-live' : '') + '" data-room="' + esc(r.room) + '" data-domain="' + esc(r.domain) + '" data-name="' + esc(r.name) + '"' +
          ' aria-label="' + esc(r.name + (live ? ': ' + live.length + ' new ' + (live.length === 1 ? 'story' : 'stories') : ': open room')) + '">' +
          '<span class="hub-story-ring"><span class="hub-story-avatar" style="background:' + color(r.room) + '">' + esc(initials(r.name)) + '</span></span>' +
          '<span class="hub-story-label">' + esc(r.name) + '</span></button>';
      }).join(''));
      row.addEventListener('click', function (e) {
        var b = e.target.closest ? e.target.closest('.hub-story[data-room]') : null; if (!b) return;
        var live = byRoom[b.getAttribute('data-room')], dom = b.getAttribute('data-domain');
        if (!live) { location.href = roomHref(dom); return; }
        viewTitle.textContent = 'Stories in ' + b.getAttribute('data-name');
        cards.innerHTML = live.map(function (it) {
          return '<div class="hub-story-card"><div class="post-meta"><span class="post-name">' + esc(it.authorName || it.roomName) + '</span>' + tierHtml(it.tier) +
            '<span class="post-time">· ' + esc(ago(typeof it.createdAt === 'number' ? new Date(it.createdAt).toISOString() : it.createdAt)) + '</span></div>' +
            '<div class="post-text">' + esc(it.text) + '</div></div>';
        }).join('') + '<a class="hub-open" href="' + esc(roomHref(dom)) + '" rel="noopener">Open ' + esc(dom) + ' →</a>';
        openDlg(view);
      });
    }).catch(function () {
      if (pickList) pickList.innerHTML = '<div class="post-empty">Stories are unavailable right now. Open a room from the list.</div>';
    });
    if (addBtn) addBtn.addEventListener('click', function () { openDlg(pick); });
  }
  var ta = document.getElementById('hub-compose-text'), sel = document.getElementById('hub-compose-room'), go = document.getElementById('hub-compose-go');
  if (ta && sel && go) {
    getJSON('/rooms.json?v=2fcf997cfb').then(function (d) {
      ((d && d.rooms) || []).forEach(function (r) {
        if (!domainOk(r.domain)) return;
        var o = document.createElement('option'); o.value = r.domain; o.textContent = r.name + ' · ' + r.domain; sel.appendChild(o);
      });
    }).catch(function () {});
    var sync = function () { go.disabled = !(ta.value.trim() && domainOk(sel.value)); };
    ta.addEventListener('input', sync); sel.addEventListener('change', sync);
    go.addEventListener('click', function () {
      var text = ta.value.trim().slice(0, 280), href = roomHref(sel.value, 'compose=' + encodeURIComponent(text));
      if (!text || !href) return;
      var gone = false, leave = function () { if (!gone) { gone = true; location.href = href; } };
      setTimeout(leave, 800);
      try { navigator.clipboard.writeText(text).then(leave, leave); } catch (e) { leave(); }
    });
  }
  Array.prototype.forEach.call(document.querySelectorAll('[data-hub-tab]'), function (b) {
    b.addEventListener('click', function () {
      var t = b.getAttribute('data-hub-tab');
      Array.prototype.forEach.call(document.querySelectorAll('[data-hub-tab]'), function (x) {
        var on = x === b; x.classList.toggle('active', on); x.setAttribute('aria-selected', on ? 'true' : 'false');
      });
      if (feed) feed.hidden = t !== 'highlights';
      if (roomsEl) roomsEl.hidden = t !== 'rooms';
      if (coming) coming.hidden = t !== 'coming';
    });
  });
})();
