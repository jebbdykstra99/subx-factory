#!/usr/bin/env python3
"""Hybrid domain config: which legacy domain is a room, a doorway into a hub topic, or parked. CONFIG ONLY.

topics/domains.json holds one entry per wave-1 doorway domain with the optional site.json fields described by
topics/site_mode.schema.json (mode room|doorway|parked, topic, brand). Nothing here writes a room repo, serves a
redirect or touches DNS; --redirects and --site-json only PRINT what a later, reviewed change would ship.

  python3 tools/topic_domains.py --check                     validate topics/domains.json against the seed, rooms and schema
  python3 tools/topic_domains.py --build [--write]           rebuild domains.json from the seed + hub/src/rooms.json
  python3 tools/topic_domains.py --redirects [--now ISO]     print the planned edge rules (302 / 301) to stdout
  python3 tools/topic_domains.py --site-json DOMAIN          print the site.json fragment for one domain to stdout
  python3 tools/topic_domains.py --validate-site FILE ...    check the optional hybrid fields in site.json files

Rules: a domain served by a live room (hub/src/rooms.json, paused or not) is mode "room"; a doorway domain of a HOLD
topic is "parked"; every other doorway domain is "doorway" to its topic. Doorways redirect
https://<domain>/* -> https://<brand.primaryDomain><brand.topicPathPrefix><slug>/?via=<domain>, 302 while the topic is
not established and 301 once it has been active 60 days (tools/topic_status.py doorway_status).
"""
import argparse, json, os, sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import topic_schema, topic_status  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOMAINS = os.path.join(ROOT, 'topics', 'domains.json')
SCHEMA = os.path.join(ROOT, 'topics', 'site_mode.schema.json')
SEED = os.path.join(ROOT, 'topics', 'seed_wave1.json')
ROOMS = os.path.join(ROOT, 'hub', 'src', 'rooms.json')
BRANDS = {'default': os.path.join(ROOT, 'brand', 'brand.json')}
HYBRID_KEYS = ('mode', 'topic', 'brand', 'doorway')


def load(p):
    return json.load(open(p, encoding='utf-8'))


def room_domains():
    return {r['domain'] for r in load(ROOMS)['rooms']}


def build(seed=None):
    seed = seed or load(SEED)
    rooms = room_domains()
    out = []
    for t in seed['topics']:
        for d in t['doorwayDomains']:
            if d in rooms:
                e = {'domain': d, 'mode': 'room', 'topic': t['slug'], 'brand': 'default'}
            elif t['status'] == 'hold':
                e = {'domain': d, 'mode': 'parked', 'topic': t['slug'], 'brand': 'default'}
            else:
                e = {'domain': d, 'mode': 'doorway', 'topic': t['slug'], 'brand': 'default',
                     'doorway': {'style': 'redirect', 'keepQuery': False}}
            out.append(e)
    out.sort(key=lambda e: e['domain'])
    return {'notes': 'CONFIG ONLY (generated by tools/topic_domains.py --build). Not served, not copied into any room repo. '
                     'Doorway status (302/301) is computed, never stored: see tools/topic_status.py doorway_status.',
            'domains': out}


def dump(d):
    return json.dumps(d, indent=2, ensure_ascii=False) + '\n'


def validate_fields(obj, where):
    sch = load(SCHEMA)
    e = ['%s: %s' % (where, x) for x in topic_schema.validate({k: obj[k] for k in obj if k in HYBRID_KEYS or k == 'domain'}, sch)]
    mode = obj.get('mode')
    if mode == 'doorway' and not obj.get('topic'):
        e.append('%s: a doorway needs a topic' % where)
    if 'doorway' in obj and mode != 'doorway':
        e.append('%s: doorway settings on a %s' % (where, mode or 'room'))
    if 'status' in (obj.get('doorway') or {}):
        e.append('%s: doorway.status is computed by tools/topic_status.py, not stored' % where)
    return e


def check(cfg=None, seed=None):
    cfg = cfg or load(DOMAINS)
    seed = seed or load(SEED)
    topics = {t['slug']: t for t in seed['topics']}
    rooms = room_domains()
    e, seen = [], set()
    for x in cfg['domains']:
        d = x.get('domain')
        w = 'domains.json %s' % d
        e += validate_fields(x, w)
        if d in seen:
            e.append('%s: listed twice' % w)
        seen.add(d)
        t = topics.get(x.get('topic'))
        if x.get('topic') and t is None:
            e.append('%s: topic %s is not in the seed' % (w, x.get('topic')))
            continue
        if x['mode'] == 'room' and d not in rooms:
            e.append('%s: mode room but no live room serves it' % w)
        if x['mode'] != 'room' and d in rooms:
            e.append('%s: a live room serves it, so it must stay mode room (no change to room repos)' % w)
        if x['mode'] == 'doorway' and t['status'] == 'hold':
            e.append('%s: doorway to a HOLD topic; park it' % w)
        if t is not None and d not in t['doorwayDomains']:
            e.append('%s: topic %s does not list it in doorwayDomains' % (w, t['slug']))
    want = {d for t in seed['topics'] for d in t['doorwayDomains']}
    for d in sorted(want - seen):
        e.append('domains.json misses seed doorway domain %s' % d)
    if dump(build(seed)) != dump(cfg):
        e.append('topics/domains.json is not what --build generates (run --build --write)')
    return e


def redirects(now, cfg=None, seed=None):
    cfg = cfg or load(DOMAINS)
    seed = seed or load(SEED)
    brand = load(BRANDS['default'])
    topics = {t['slug']: t for t in seed['topics']}
    lines = []
    for x in cfg['domains']:
        if x['mode'] != 'doorway':
            lines.append('# %s: mode %s, no redirect' % (x['domain'], x['mode']))
            continue
        st = topic_status.doorway_status(topics[x['topic']], now)
        lines.append('https://%s/*  https://%s%s%s/?via=%s  %d' % (x['domain'], brand['primaryDomain'], brand['topicPathPrefix'],
                                                                 x['topic'], x['domain'], st))
    return lines


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--redirects', action='store_true')
    ap.add_argument('--now')
    ap.add_argument('--site-json')
    ap.add_argument('--validate-site', nargs='+')
    a = ap.parse_args(argv)
    if a.build:
        b = dump(build())
        if a.write:
            open(DOMAINS, 'w', encoding='utf-8').write(b)
            print('wrote topics/domains.json')
        else:
            sys.stdout.write(b)
        return 0
    if a.redirects:
        now = a.now or datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
        print('# PLAN ONLY (not served): doorway edge rules at %s' % now)
        print('\n'.join(redirects(now)))
        return 0
    if a.site_json:
        hit = [x for x in load(DOMAINS)['domains'] if x['domain'] == a.site_json]
        if not hit:
            print('unknown domain %s' % a.site_json, file=sys.stderr)
            return 1
        print(json.dumps({k: v for k, v in hit[0].items() if k in HYBRID_KEYS}, indent=2))
        return 0
    if a.validate_site:
        errs = []
        for p in a.validate_site:
            errs += validate_fields(load(p), p)
        print('\n'.join(errs) or 'site.json hybrid fields OK (%d files)' % len(a.validate_site))
        return 1 if errs else 0
    errs = check()
    if errs:
        print('\n'.join('FAIL ' + x for x in errs), file=sys.stderr)
        return 1
    modes = {}
    for x in load(DOMAINS)['domains']:
        modes[x['mode']] = modes.get(x['mode'], 0) + 1
    print('domains.json OK: %d domains %s' % (sum(modes.values()), modes))
    return 0


if __name__ == '__main__':
    sys.exit(main())
