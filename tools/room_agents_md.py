#!/usr/bin/env python3
"""Render a room-specific AGENTS.md for one SubX room clone.

Inputs: the room clone (site.json, files present) + subx-factory rooms.json + EXCEPTIONS.md.
Usage:  python3 tools/room_agents_md.py <room-clone-dir> [--room NAME] > AGENTS.md
Used by tools/fanout.py (template-sync mode). Output stays well under Devin/Cursor's 16 KiB
AGENTS.md auto-inject limit.
"""
import argparse, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
FACTORY = os.path.dirname(HERE)
PUBLIC_PHONE = "+1-650-539-5005"
ALIASES = {"behindtheblackwall": "btb", "airlineschat": "airlines", "amachat": "ama"}


def load_rooms():
    with open(os.path.join(FACTORY, "rooms.json")) as f:
        return json.load(f)


def exception_rows(room, short):
    """EXCEPTIONS.md table rows that name this room (by repo name or short name)."""
    path = os.path.join(FACTORY, "EXCEPTIONS.md")
    if not os.path.exists(path):
        return []
    rows = []
    names = {room, short, room.replace("chat", ""), ALIASES.get(room, room)}
    for line in open(path, encoding="utf-8"):
        if not re.match(r"^\| E\d+ ", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 6:
            continue
        rooms_cell = cells[1]
        toks = {t.strip().lower() for t in re.split(r"[ ,]+", rooms_cell) if t.strip()}
        if toks & {n.lower() for n in names if n}:
            what = cells[2] if "`" in cells[2] else f"`{cells[2]}`"
            rows.append(f"- **{cells[0]}** {what} ({cells[3]}): {cells[5]}")
    return rows


def render(clone, room_name=None):
    with open(os.path.join(clone, "site.json"), encoding="utf-8") as f:
        site = json.load(f)
    rooms = load_rooms()
    owner = rooms.get("owner", "jebbdykstra99")
    room_name = room_name or os.path.basename(os.path.abspath(clone))
    r = next((x for x in rooms["rooms"] if x["room"] == room_name), {})
    domain = r.get("domain") or site.get("domain") or f"{room_name}.com"
    site_id = site.get("siteId") or r.get("siteId")
    nests = site.get("nests") or []
    nest_slugs = [n.get("slug") for n in nests if isinstance(n, dict) and n.get("slug")]
    has_gate = os.path.exists(os.path.join(clone, "gate.js"))
    keep = r.get("keepFiles", [])
    gate_core = "gate.js" in keep and room_name in ("311chat", "atmchat")
    min_age = site.get("minAge", 13 if "minAge" not in site else site["minAge"])
    status = r.get("status", "unknown")
    wait = r.get("waitFor") or []
    preview = site.get("preview", True)
    exc = exception_rows(room_name, (site_id or "").lower())

    if gate_core:
        gate_line = (f"`gate.js` **is present and kept** here: location is core to {room_name} "
                     "(EXCEPTIONS E1, `rooms.json keepFiles`). Do not remove it, and do not copy it to any other room.")
    elif has_gate:
        gate_line = ("`gate.js` exists in this repo but location is **not** recorded as core for this room. "
                     "Do not extend it; its fate is Jebb's call (see EXCEPTIONS). Never add gate.js anywhere else.")
    else:
        gate_line = "**No `gate.js`.** This room is not a location room. Do not add one (gate.js only where location is core: 311chat, atmchat)."

    lines = []
    A = lines.append
    A(f"# AGENTS.md: {room_name}")
    A("")
    A(f"Guide for coding agents (Cursor, Devin, Codex, Claude Code) working in `{owner}/{room_name}`. "
      "Generated by `subx-factory/tools/room_agents_md.py`; change the generator, not just this file.")
    A("")
    A("## What this repo is")
    A(f"- **{site.get('name', room_name)}**: {site.get('tagline', '').strip() or 'SubX room'} One SubX room (a themed micro-social feed) served at **https://{domain}**.")
    A(f"- `siteId`: **`{site_id}`** (Firestore docs are keyed by it in the shared Firebase project `subx-skins`).")
    A(f"- Factory status: `{status}` (cluster `{r.get('cluster', '?')}`, stamp order {r.get('order', '?')})"
      + (f"; waiting on: {'; '.join(wait)}" if wait else "") + ".")
    if r.get("notes"):
        A(f"- Note: {r['notes']}")
    A(f"- Nests ({len(nest_slugs)}): " + (", ".join(f"`{s}`" for s in nest_slugs[:40]) if nest_slugs else "defined in `site.json`") + ".")
    A(f"- Age gate: {min_age}+ (`site.json minAge`, default 13).")
    A("")
    A("## Layout")
    A("- `index.html`: shell. `factory.js`: the shared SubX client (**owned by subx-factory, never edit by hand here**). `site.json`: all room-specific data (theme, nests, rail, copy). `styles.css`: room skin.")
    A("- `<nest>.html`: static nest pages; `404.html` bounces `/{slug}` to the shell. `_redirects` is kept for parity (inert on GitHub Pages).")
    A("- `terms.html`, `privacy.html`, `about.html`: legal and about pages (CLO-owned copy).")
    A("- `tests/smoke/`: shared Playwright smoke test (synced from subx-factory `templates/room`). `.github/workflows/smoke.yml`: runs it on every PR.")
    A("")
    A("## Deploy path")
    A(f"- **GitHub Pages, legacy build from `main`** (`CNAME` = `{domain}`). Anything merged to `main` is live within minutes. There is no build step.")
    A("- `factory.js` changes arrive only as **stamp PRs from subx-factory** (`tools/stamp.py`, which writes `FACTORY.lock`). Code differences need a row in subx-factory `EXCEPTIONS.md`.")
    A("- Firestore/Storage rules are **not** in this repo's deploy path. Jebb publishes them by hand in the Firebase console. Never run `firebase deploy` from here.")
    A("- Agents open **PRs only**. Jebb merges. No direct pushes to `main`, no force-push, no DNS/Pages-settings changes.")
    A("")
    A("## Locks (do not change without Jebb)")
    A(f"1. **Preview lock:** `<meta name=\"robots\" content=\"noindex, nofollow\">`, `robots.txt Disallow: /`, `site.json preview: {str(preview).lower()}` and the preview banner stay **until Jebb lifts this room**. Do not remove noindex or the banner in any PR.")
    A(f"2. **gate.js:** {gate_line}")
    plus_sel = "`.nav-nests-add` (this room's E7 fork)" if room_name in ("airlineschat", "amachat") else "`#nav-nest-add`"
    A(f"3. **Nests are mandatory.** The Nests nav group, nest links, and the `+` (add a nested room, {plus_sel}) must render on Home. Never hide or remove them.")
    A(f"4. **One public phone number:** **{PUBLIC_PHONE}** is the only phone number allowed in shipped files (legal pages, contact). Do not add any other number (third-party public listings such as city 311 lines are data, not our contact).")
    A("5. No inline Firebase web key (`AIza…`) in any file (hosted config only). No new third-party scripts, trackers, paid services, or signups.")
    A("6. No placeholder copy on Home (the smoke test fails on `Dummy feed`). Legal/age copy changes go through the CLO.")
    if exc:
        A("")
        A("## Recorded exceptions for this room (subx-factory EXCEPTIONS.md)")
        lines.extend(exc)
    A("")
    A("## How to run tests")
    A("```bash")
    A("cd tests/smoke")
    A("npm install")
    A("npx playwright install chromium   # or: SMOKE_CHROME=/usr/bin/google-chrome npm test")
    A("npm test                          # serves the repo root on 127.0.0.1:4173 and runs smoke.spec.mjs")
    A("```")
    A("- Checks: Home loads; Nests nav + `+` visible; no `Dummy feed` text; `noindex` present unless the room is lifted (`site.json preview: false`, or `SMOKE_LIFTED=1`).")
    A("- Read-only: no sign-in, no writes. Cloud Functions, the visit pixel and analytics are blocked in the test.")
    A("- `SMOKE_BASE_URL=https://example.test npm test` runs it against a running copy instead of a local server.")
    A("- CI: `.github/workflows/smoke.yml` runs on every pull request (free GitHub Actions minutes on this public repo). A PR must be green before Jebb merges.")
    A("")
    A("## Before you open a PR")
    A("- Keep the change scoped to this room. Shared logic belongs in subx-factory.")
    A(f"- Run the smoke test. Grep for phone numbers (`{PUBLIC_PHONE}` only) and `AIza`.")
    A("- Say in the PR body what changes on the live site after merge.")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("clone")
    ap.add_argument("--room")
    a = ap.parse_args()
    sys.stdout.write(render(a.clone, a.room))
